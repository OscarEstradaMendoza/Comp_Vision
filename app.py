def allowed_file(filename: str) -> bool:
    """
    Validate that the uploaded file has an allowed extension.
    
    This security check prevents users from uploading potentially dangerous file types.
    Only image files with recognized extensions are allowed.
    
    Args:
        filename (str): The name of the uploaded file
    
    Returns:
        bool: True if the file extension is in the ALLOWED_EXTENSIONS set, False otherwise
    
    Example:
        >>> allowed_file("image.jpg")
        True
        >>> allowed_file("script.exe")
        False
    """
    # Check if filename contains a dot (indicating an extension)
    # and if the extension (lowercased) is in the allowed set
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS


# ============================================================================
# ROUTE HANDLERS
# ============================================================================
@app.route('/', methods=['GET', 'POST'])
def index():
    """
    Main route handler for the application.
    
    Handles both GET and POST requests:
    - GET: Displays the upload form (empty state or with previous results)
    - POST: Processes image upload, generates caption, creates audio, and displays results
    
    Workflow for POST requests:
    1. Validate file upload and extract mode/emotion preferences
    2. Save uploaded image to disk
    3. Generate base caption using BLIP model
    4. Transform caption based on selected mode
    5. Generate audio file with selected emotion
    6. Render template with all results
    
    Returns:
        Rendered HTML template with:
            - uploaded_image: Path to the uploaded image (if uploaded)
            - caption: Generated/transformed caption text
            - audio_path: Path to generated audio file
            - mode: Selected caption mode
            - emotion: Selected audio emotion
    """
    # Initialize variables for template rendering
    uploaded_image = None  # Path to uploaded image file
    caption = None        # Generated/transformed caption text
    audio_path = None     # Path to generated audio file
    mode = 'caption'      # Default caption mode
    emotion = 'calm'      # Default audio emotion
    
    # ========================================================================
    # POST REQUEST HANDLING - Process file upload
    # ========================================================================
    if request.method == 'POST':
        # Extract user preferences from form data
        # These determine how the caption is transformed and how audio is generated
        mode = request.form.get('mode', 'caption')      # Caption transformation mode
        emotion = request.form.get('emotion', 'calm')   # Audio emotion style
        
        # Validate that a file was included in the request
        if 'file' not in request.files:
            flash('No file selected')
            return redirect(request.url)
        
        file = request.files['file']
        
        # Check if user actually selected a file (not just empty form submission)
        if file.filename == '':
            flash('No file selected')
            return redirect(request.url)
        
        # ====================================================================
        # FILE VALIDATION AND SAVING
        # ====================================================================
        if file and allowed_file(file.filename):
            # Sanitize filename to prevent directory traversal attacks
            # secure_filename removes dangerous characters and path components
            filename = secure_filename(file.filename)
            
            # Ensure upload directories exist (create if they don't)
            os.makedirs(app.config['UPLOAD_FOLDER'], exist_ok=True)
            os.makedirs(app.config['AUDIO_FOLDER'], exist_ok=True)
            
            # Construct full file path and save the uploaded file
            filepath = os.path.join(app.config['UPLOAD_FOLDER'], filename)
            file.save(filepath)
            uploaded_image = filepath  # Store path for template rendering
            
            # ================================================================
            # CAPTION GENERATION
            # ================================================================
            try:
                logger.info(f"Generating caption for image: {filepath}")
                
                # Generate base caption using BLIP model
                # This is the plain description of the image
                base_caption = generate_caption(filepath)
                logger.info(f"Base caption: {base_caption}")

                # Transform the caption based on selected mode
                # This applies creative transformations (story, poetic, funny, etc.)
                caption = apply_mode_to_caption(base_caption, mode)
                logger.info(f"Final text for mode '{mode}': {caption}")

                # ============================================================
                # AUDIO GENERATION
                # ============================================================
                # Generate audio only if caption was successfully created
                if caption and caption != "Unable to generate caption":
                    try:
                        logger.info("Generating audio from caption...")
                        
                        # Convert text to speech with selected emotion
                        # The emotion parameter affects audio processing (speed, volume, effects)
                        audio_path = text_to_audio(
                            caption,                    # Text to convert to speech
                            app.config['AUDIO_FOLDER'], # Directory to save audio file
                            filename,                    # Base filename for audio file
                            emotion                      # Emotion style for audio processing
                        )
                        
                        if audio_path:
                            logger.info(f"Audio generated successfully: {audio_path}")
                        else:
                            logger.warning("Failed to generate audio")
                    except Exception as e:
                        # Log error but continue - image and caption will still be displayed
                        logger.error(f"Error generating audio: {str(e)}")
                        flash(f'Error generating audio: {str(e)}')
            except Exception as e:
                # Log caption generation error
                logger.error(f"Error generating caption: {str(e)}")
                flash(f'Error generating caption: {str(e)}')
                # Set fallback caption so image can still be displayed
                caption = "Unable to generate caption"
        else:
            # Invalid file type - show error and redirect
            flash('Invalid file type. Please upload an image (png, jpg, jpeg, gif, webp)')
            return redirect(request.url)
    
    # ========================================================================
    # RENDER TEMPLATE
    # ========================================================================
    # Render the HTML template with all the data
    # Template will display upload form, image, caption, and audio player
    return render_template(
        'index.html',
        uploaded_image=uploaded_image,
        caption=caption,
        audio_path=audio_path,
        mode=mode,
        emotion=emotion
    )


# ============================================================================
