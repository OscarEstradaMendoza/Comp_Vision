# ============================================================================
# FILE VALIDATION
# ============================================================================
# Set of allowed image file extensions for security
# Only these formats will be accepted for upload
ALLOWED_EXTENSIONS = {'png', 'jpg', 'jpeg', 'gif', 'webp'}


def apply_mode_to_caption(caption: str, mode: str) -> str:
    """
    Transform a base image caption into different creative formats based on the selected mode.
    
    This function takes the plain caption generated by the BLIP model and applies creative
    transformations to create different narrative styles. Each mode has multiple variations
    that are randomly selected to provide variety.
    
    Args:
        caption (str): The base caption generated by the BLIP model (plain text description)
        mode (str): The transformation mode to apply. Valid options:
            - 'caption': Enhanced captions with cyberpunk-themed additions
            - 'story': Full narrative stories with opening, middle, twist, and ending
            - 'poetic': Multi-line poetry with cyberpunk imagery
            - 'funny': Humorous captions with tech-related punchlines
    
    Returns:
        str: The transformed caption text based on the selected mode.
             Returns the original caption if mode is invalid or caption is empty.
    
    Note:
        The function uses random selection for variations within each mode to ensure
        different outputs even with the same base caption.
    """
    # Early return if caption is empty or None
    if not caption:
        return caption

    # Clean up the base caption: remove trailing periods and whitespace
    base = caption.strip().rstrip(".")
    
    # Create a lowercase version for natural sentence integration
    # This is used in story mode to make the caption flow naturally in sentences
    scene = base[0].lower() + base[1:] if len(base) > 1 else base

    # ========================================================================
    # MODE: CAPTION - Enhanced captions with cyberpunk atmosphere
    # ========================================================================
    if mode == "caption":
        # Multiple variations of enhanced captions with cyberpunk-themed additions
        variants = [
            base,  # Original caption
            f"{base}. A moment frozen in neon light.",
            f"{base}, framed by the distant hum of the city.",
            f"{base}. It looks like a still from a sci-fi movie.",
            f"{base}. You can almost hear the electricity in the air.",
        ]
        return random.choice(variants)

    # ========================================================================
    # MODE: STORY - Full narrative with cyberpunk storytelling elements
    # ========================================================================
    if mode == "story":
        # Opening sentences that set a cyberpunk scene
        openings = [
            f"In a forgotten corner of the city, {scene}.",
            f"On a night when the neon refused to sleep, {scene}.",
            f"Somewhere between dream and glitch, {scene}.",
        ]
        
        # Middle sections that build atmosphere with cyberpunk imagery
        middles = [
            " Rain slid down chrome and glass, turning every light into a streak of color.",
            " The streets hummed with drones, tired footsteps, and quiet conversations no one was meant to hear.",
            " Above, billboards argued in looping holograms while the sky pretended not to notice.",
        ]
        
        # Plot twists that add intrigue to the narrative
        twists = [
            " Someone passing by felt the strange certainty that this moment mattered.",
            " A stranger stopped, saving the scene in their memory like a secret file.",
            " No one realized this tiny scene would start a chain of events that couldn't be undone.",
        ]
        
        # Ending sentences that provide closure with cyberpunk themes
        endings = [
            " By morning, the city would be exactly the same—except for one person who finally decided to change.",
            " When the sun finally pushed through the clouds, the world looked identical, but the story had already shifted.",
            " Long after the lights dimmed, the echo of that moment kept rewriting itself in the network's memory.",
        ]

        # Combine random selections from each section to create a unique story
        story = random.choice(openings) + random.choice(middles) + \
                random.choice(twists) + " " + random.choice(endings)
        return story

    # ========================================================================
    # MODE: POETIC - Multi-line poetry with cyberpunk imagery
    # ========================================================================
    if mode == "poetic":
        # Different poetic templates, each with the caption as the first line
        templates = [
            f"{base}.\n"
            "Neon drips down the glass,\n"
            "Shadows lean into the rain,\n"
            "Circuits whisper under tired boots,\n"
            "And the city pretends not to dream.",

            f"{base}.\n"
            "Pixels blur into midnight,\n"
            "Billboards breathe electric prayers,\n"
            "Somewhere, a quiet signal blinks,\n"
            "waiting for someone to notice.",

            f"{base}.\n"
            "Chrome and moonlight share a secret,\n"
            "Cables curl like restless thoughts,\n"
            "A heartbeat hides in every screen,\n"
            "and the future watches from the corner.",
        ]
        return random.choice(templates)

    # ========================================================================
    # MODE: FUNNY - Humorous captions with tech-related humor
    # ========================================================================
    if mode == "funny":
        # Setup phrases that introduce the caption in a humorous context
        setups = [
            f"{base.capitalize()}, which is exactly what happens",
            f"{base.capitalize()} — honestly, this is what you get",
            f"{base.capitalize()}. This is the natural result",
        ]
        
        # Punchline phrases that add tech humor
        punches = [
            " when you let an AI design the future after three energy drinks.",
            " when nobody reads the terms and conditions but clicks accept anyway.",
            " when the Wi-Fi is strong but the life choices are weak.",
            " when someone says, 'How bad could it be?' and the universe takes it personally.",
        ]
        
        # Ending phrases that add a final humorous touch
        endings = [
            " Somewhere, a server is facepalming in 4K.",
            " An AI just added this to its 'are you sure?' folder.",
            " The cloud is laughing, but your storage is full.",
        ]
        return random.choice(setups) + random.choice(punches) + " " + random.choice(endings)

    # Default: return the original caption if mode is not recognized
    return caption


